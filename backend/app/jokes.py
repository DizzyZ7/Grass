JOKES = {f'{kind}_{i:02d}': (kind, line) for kind, lines in LINES.items() for i, line in enumerate(lines, 1)}


def pick_joke(kind: str, recent: list[str], seed: str) -> tuple[str, str, list[str]]:
    options = [(id_, line) for id_, (event, line) in JOKES.items() if event == kind and id_ not in recent]
    if not options:
        options = [(id_, line) for id_, (event, line) in JOKES.items() if event == kind]
    if not options:
        raise ValueError('Unknown joke event')
    index = int.from_bytes(hashlib.sha256(seed.encode()).digest()[:4], 'big') % len(options)
    chosen, line = options[index]
    return chosen, line, (recent + [chosen])[-8:]
